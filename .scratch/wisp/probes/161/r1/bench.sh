#!/bin/sh
# bench.sh - ticket 161 AC#1 (r1 slice): does each D22 ban actually RING today?
#
# WHAT THIS IS. A fixture bench for the static gate `tools/d22scan`. For every
# numbered ban in tools/d22scan/main.go's `// Bans` roster it builds
#   (a) a known-violation sample root, and
#   (b) a known-clean sample root of the same shape,
# runs the scanner over that root with `-root`, and records whether the ban
# rang. The clean twin is not a courtesy: a sample that rings proves nothing
# unless the same-shaped clean sample stays silent (this repo has rejected two
# always-true criteria already).
#
# HOW IT WORKS AND WHY NOTHING LANDS IN THE TREE. The scanner takes exactly one
# knob, `-root <dir>` (tools/d22scan/main.go: main() -> checkRoot -> Scan). So a
# sample is a *fake repository root* laid out the way checkRoot demands:
# go.mod + tools/d22scan/allowlist.txt + internal/ + cmd/, with >= 10 production
# .go files, and every declared live scope non-empty (else the run exits 2 on
# "an empty instrument is not a verdict" instead of answering the question).
# Those roots live under
#   .scratch/wisp/probes/161/r1/runs/<cell>/...
# which is GENERATED by this script, never committed, and never inside internal/,
# cmd/, frontend/ or design/ of the real tree. The production bytes are not
# touched by anything here: this script reads tools/d22scan/** and writes only
# under its own directory.
#
# The generated roots are byte-identical for a given commit of THIS file, so a
# reading is recomputable: `sh bench.sh all` reproduces logs/<cell>.scan.log.
#
# SUBCOMMANDS
#   sh bench.sh build <cell>            instantiate runs/<cell>/ only
#   sh bench.sh run <cell>              build + scan + write logs/<cell>.scan.log
#   sh bench.sh all                     every cell, then logs/summary.tsv
#   sh bench.sh tool                    build the scanner binary into bin/
#   sh bench.sh gorun <cell>            same cell through `go run .` (proves the
#                                       binary under bin/ is not a stale stand-in)
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)      # probes/161/r1
# r1 -> 161 -> probes -> wisp -> .scratch -> repo root: five levels up.
root=$(CDPATH= cd -- "$here/../../../../.." && pwd)    # repository root
[ -f "$root/go.mod" ] || { echo "bench.sh: derived root \"$root\" has no go.mod - refusing" >&2; exit 2; }
cells="$here/cells"
runs="$here/runs"
logs="$here/logs"
bin="$here/bin/d22scan-probe161.exe"

# The cell roster. Order is: the skeleton control first (it is the reading that
# says "this layout itself is silent", so every other silence is attributable),
# then the ban order of main.go's `// Bans` block, then the `unparseable`
# finding type last.
CELLS="
skeleton-clean
b1-closure-bad
b1-named-bad
b1-clean
b1-probe-testfile
b2-bad
b2-clean
b2-probe-alias
b3-bad
