func base(p string) string { return filepath.Base(p) }

func dir(p string) string { return filepath.Dir(p) }

func rel(a, b string) (string, error) { return filepath.Rel(a, b) }

type fakeResolver struct{}

func (fakeResolver) Clean() string { return "." }
GOEOF
        ;;
    b2-probe-alias)
        cat >"$d/internal/a/p_b2.go" <<'GOEOF'
package a

import fp "path/filepath"

// Cell b2-probe-alias: the SAME filesystem decision, reached through an aliased
// import. The ban's wording ("filepath.Clean / filepath.Abs outside the
// allowlist") does not license an alias; the matcher keys on the local
// identifier name. This cell exists to read out which of the two the gate
// implements.
func norm(p string) string { return fp.Clean(p) }
GOEOF
        ;;

    # ---- ban #3 plaintext-key (AST ValueSpec + AssignStmt, shape-guarded)
    b3-bad)
        cat >"$d/internal/a/p_b3.go" <<'GOEOF'
