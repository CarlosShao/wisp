# ---------------------------------------------------------------- driver -----
build() {
    cell=$1
    d="$runs/$cell"
    mkdir -p "$d"
    skeleton "$d"
    payload "$cell" "$d"
    echo "$cell" >"$d/.cell"
}

tool() {
    mkdir -p "$here/bin"
    ( cd "$root/tools/d22scan" && go build -o "$bin" . )
    echo "built: $bin from tools/d22scan at $root"
}

run() {
    cell=$1
    build "$cell"
    mkdir -p "$logs"
    out="$logs/$cell.scan.log"
    {
        echo "# cell: $cell"
        echo "# command: (cd \"$root/tools/d22scan\" && $bin -root \"$runs/$cell\")"
    } >"$out"
    # `|| rc=$?` instead of a set +e/-e pair: a function that re-enables errexit
    # is a function that kills its caller's loop one line later.
    rc=0
    ( cd "$root/tools/d22scan" && "$bin" -root "$runs/$cell" ) >>"$out" 2>&1 || rc=$?
    echo "# rc=$rc" >>"$out"
    return $rc
}

summary() {
    mkdir -p "$logs"
    t="$logs/summary.tsv"
    printf 'cell\texpected_ban\texpectation\trc\tring_count\trig_said_ban\tfinding_lines\n' >"$t"
    for cell in $CELLS; do
        out="$logs/$cell.scan.log"
        [ -f "$out" ] || { echo "bench.sh: missing log for $cell" >&2; continue; }
        rc=$(sed -n 's/^# rc=//p' "$out")
        spec=$(expect_of "$cell")
        ban=${spec%%|*}
        exp=${spec##*|}
        hits=$(grep -cE '^[A-Za-z0-9_./-]+:[0-9]+: \[' "$out" || true)
        said=no
        if [ "$ban" != "-" ] && grep -qE ": \[$ban\] " "$out"; then said=yes; fi
        lines=$(grep -E '^[A-Za-z0-9_./-]+:[0-9]+: \[' "$out" | tr '\n' '~' || true)
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$cell" "$ban" "$exp" "$rc" "$hits" "$said" "$lines" >>"$t"
    done
    column -t -s '	' "$t"
}

all() {
    tool
    for cell in $CELLS; do
        set +e
        run "$cell"
        rc=$?
        set -e
        echo "cell=$cell rc=$rc"
    done
    summary
}

gorun() {
    cell=$1
    build "$cell"
    ( cd "$root/tools/d22scan" && go run . -root "$runs/$cell" )
    echo "# go run rc=$?"
}

case ${1:-} in
build)   build "$2" ;;
run)     set +e; run "$2"; echo "rc=$?"; ;;
all)     all ;;
tool)    tool ;;
gorun)   set +e; gorun "$2"; ;;
cells)   for c in $CELLS; do echo $c; done ;;
*)       echo "usage: sh bench.sh {all|build <cell>|run <cell>|gorun <cell>|tool|cells}" >&2; exit 2 ;;
esac
