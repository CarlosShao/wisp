b3-probe-structlit
b4-sub-bad
b4-unix-bad
b4-clean
b5-bad
b5-clean
b6-bad
b6-clean
b6-probe-comment
b7-bad
b7-clean
b8-scope-bad
b8-comment-clean
b8-probe-bands
unp-bad
unp-hides-bans
al-overbroad
"

# What each cell is expected to do, as "<ban-tag>|<expect>", expect = ring |
# silent | unknown (a probe measures, it does not assert). Written out here so
# the summary table can be read without opening the payloads.
expect_of() {
    case $1 in
    skeleton-clean)    echo "-|silent" ;;
    b1-closure-bad)    echo "bare-goroutine|ring" ;;
    b1-named-bad)      echo "bare-goroutine|ring" ;;
    b1-clean)          echo "bare-goroutine|silent" ;;
    b1-probe-testfile) echo "bare-goroutine|unknown" ;;
    b2-bad)            echo "pathresolver-bypass|ring" ;;
    b2-clean)          echo "pathresolver-bypass|silent" ;;
    b2-probe-alias)    echo "pathresolver-bypass|unknown" ;;
    b3-bad)            echo "plaintext-key|ring" ;;
    b3-clean)          echo "plaintext-key|silent" ;;
    b3-probe-structlit) echo "plaintext-key|unknown" ;;
    b4-sub-bad)        echo "wallclock-timeout|ring" ;;
    b4-unix-bad)       echo "wallclock-timeout|ring" ;;
    b4-clean)          echo "wallclock-timeout|silent" ;;
    b5-bad)            echo "mirror-hash|ring" ;;
    b5-clean)          echo "mirror-hash|silent" ;;
    b6-bad)            echo "panel-approval|ring" ;;
    b6-clean)          echo "panel-approval|silent" ;;
    b6-probe-comment)  echo "panel-approval|unknown" ;;
    b7-bad)            echo "internal-artifact-tool|ring" ;;
    b7-clean)          echo "internal-artifact-tool|silent" ;;
    b8-scope-bad)      echo "emoji|ring" ;;
    b8-comment-clean)  echo "emoji|silent" ;;
    b8-probe-bands)    echo "emoji|unknown" ;;
    unp-bad)           echo "unparseable|ring" ;;
    unp-hides-bans)    echo "bare-goroutine|unknown" ;;
    al-overbroad)      echo "pathresolver-bypass|silent" ;;
    *)                 echo "?|unknown" ;;
    esac
}

# ---------------------------------------------------------------- skeleton ----
# One fake wisp root. Everything in it is inert: no ban may ring on it, and its
# shape is exactly what checkRoot()/declaredScopes() demand, so an rc of 2
# ("empty instrument") can never masquerade as an answer.
skeleton() {
    d=$1
    mkdir -p "$d/tools/d22scan" "$d/internal/a" "$d/internal/tools" \
             "$d/cmd/probe" "$d/frontend" "$d/design"
    printf 'module probe161.example/fixture\n\ngo 1.24\n' >"$d/go.mod"
    # Deliberately EMPTY allowlist (comments only): a clean reading here must
    # mean "nothing matched", never "something suppressed it".
    {
        echo '# probe-bench allowlist for ticket 161 r1 - intentionally empty.'
        echo '# A clean verdict below means no rule matched; nothing is suppressed here.'
    } >"$d/tools/d22scan/allowlist.txt"
    # 10 production .go files live here (9) + cmd (1) = 10, plus internal/tools.
    i=0
    while [ $i -lt 9 ]; do
        printf 'package a\n\n// Skeleton file %d of the ticket-161 r1 probe bench.\nfunc Keep%d() int { return %d }\n' "$i" "$i" "$i" >"$d/internal/a/skeleton$i.go"
        i=$((i + 1))
    done
    printf 'package tools\n\n// Skeleton carrier for ban #7 scope internal/tools/.\nfunc ToolName() string { return "artifacts.list" }\n' >"$d/internal/tools/probe_tool.go"
    printf 'package main\n\n// Skeleton carrier for cmd/ (bans #1-5 + ban #8 scope cmd/).\nfunc main() { _ = 1 }\n' >"$d/cmd/probe/main.go"
    printf 'export const skeleton = 1\n' >"$d/frontend/skeleton.ts"
    printf '<!doctype html>\n<title>probe skeleton</title>\n' >"$d/design/skeleton.html"
}

# ---------------------------------------------------------------- payloads ---
payload() {
    cell=$1
    d=$2
    case $cell in
    skeleton-clean)
        # control: nothing added on top of the skeleton
        :
        ;;

    # ---- ban #1 bare-goroutine (AST *ast.GoStmt, scope internal/+cmd/ non-test)
    b1-closure-bad)
        cat >"$d/internal/a/p_b1.go" <<'GOEOF'
package a

// Cell b1-closure-bad. The pre-R16 matcher saw ONLY this shape, so "clean" used
// to mean "no bare closures" rather than "nothing bypasses Spawn".
func spawnClosure() {
	go func() { _ = 1 }()
}
GOEOF
        ;;
    b1-named-bad)
        cat >"$d/internal/a/p_b1.go" <<'GOEOF'
package a

func probeReader() { _ = 1 }

// Cell b1-named-bad: R16#1's widening - a NAMED call spawns exactly as unsafely
// as the closure above, and it is the shape the gate used to be blind to.
func spawnNamed() { go probeReader() }
GOEOF
        ;;
    b1-clean)
        cat >"$d/internal/a/p_b1.go" <<'GOEOF'
package a

func probeReader() { _ = 1 }

// Cell b1-clean. Same file, same words, no `go` keyword: the sanctioned spawn
// point is observe.Registry.Spawn, spelled here as a plain call because this
// fake root carries no observe package. The banned shapes appear in this
// comment as PROSE only (go func() {}() and go probeReader()), which is exactly
// what an AST ban must not fire on and a text grep would.
func spawnSanctioned() { RegistrySpawn(probeReader) }

func RegistrySpawn(fn func()) { fn() }
GOEOF
        ;;
    b1-probe-testfile)
        # Scope probe, not a blind spot: bans #1-5 are production, non-test by
        # declaration (main.go's doc comment). Measured anyway, because nobody
        # has ever read the number.
        cat >"$d/internal/a/p_b1_test.go" <<'GOEOF'
package a

func TestSpawnShape(t *testing.T) {
	go func() { _ = 1 }()
}
GOEOF
        ;;

    # ---- ban #2 pathresolver-bypass (AST selector, receiver named `filepath`)
    b2-bad)
        cat >"$d/internal/a/p_b2.go" <<'GOEOF'
package a

import "path/filepath"

// Cell b2-bad: both arms of the ban, in production scope, and this fixture's
// allowlist is empty, so nothing here is a sanctioned exception.
func norm(p string) string { return filepath.Clean(p) }

func absOf(p string) (string, error) { return filepath.Abs(p) }
GOEOF
        ;;
    b2-clean)
        cat >"$d/internal/a/p_b2.go" <<'GOEOF'
package a

import "path/filepath"

// Cell b2-clean: the sibling filepath calls that are NOT the banned pair, plus
// a same-named method on a different receiver - the ban is about Clean/Abs on
// the stdlib package, not about the word "Clean".
